/** Each invocation returns independent, editable values. */
export function getTypeDefaults(type = '학생단체') {
  const settings = typeSettings[type] || typeSettings['기타'];
  const operation = typeOperations[type] || typeOperations['기타'];
  const templates = JSON.parse(JSON.stringify(DEFAULT_MESSAGE_TEMPLATES));
  templates.interview.text += `\n${operation[1]}`;
  const criteria = settings.criteria.map(id => ({
    id, label: criterionDefinitions[id][0], max: 20, description: criterionDefinitions[id][1],
    rubric: '예시: 구체적인 근거와 실행 방법이 충분함 16~20점 / 일부 근거가 있으나 설명 보완이 필요함 8~15점 / 관련 설명이 부족함 0~7점. 담당자가 기준을 조정해 사용하세요.',
  }));
  return {
    targetScore: 100, criteria, materials: settings.materials,
    questions: QUESTION_BANK.filter(q => settings.fields.includes(q.field)).map((q, index) => ({ ...q, selected: index < 3, criterionId: settings.criteria.includes(q.criterionId) ? q.criterionId : '' })),
    templates,
    checklist: [...CHECKLIST_ITEMS.map(item => ({ ...item })), { id: 'type-operation', label: operation[0], done: false, due: '', note: '모집 공고와 실제 운영조건을 확인한 뒤 사용하세요.' }],
  };
}
